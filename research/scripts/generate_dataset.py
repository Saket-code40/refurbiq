def weighted_choice(rng: random.Random, mapping: dict[str, float]) -> str:
    keys = list(mapping)
    weights = [mapping[k] for k in keys]
    return rng.choices(keys, weights=weights, k=1)[0]


def sentiment_for(aspect: str, platform: str, rng: random.Random) -> str:
    probs = dict(BASE_SENTIMENT)
    for label, delta in PLATFORM_BIAS.get(platform, {}).get(aspect, {}).items():
        probs[label] += delta
    # Re-normalise and clamp.
    probs = {k: max(v, 0.01) for k, v in probs.items()}
    total = sum(probs.values())
    probs = {k: v / total for k, v in probs.items()}
    return weighted_choice(rng, probs)


def rating_from(mentions: list[tuple[str, str]], rng: random.Random) -> int:
    """Rating correlated with the mix of aspect sentiments (1-5)."""
    score_of = {"positive": 5, "neutral": 3, "negative": 1}
    base = sum(score_of[m["sentiment"]] for m in mentions) / len(mentions)
    noisy = base + rng.uniform(-0.6, 0.6)
    return max(1, min(5, round(noisy)))


def build_review(
    review_id: int, platform: str, category: str, product: str, rng: random.Random
) -> tuple[str, list[dict], int, str]:
    """Return (review_text, aspect_mention_rows, rating, review_date)."""
    brand = product.split()[0] if " " in product else product
    n_aspects = rng.choices([1, 2, 3], weights=[0.45, 0.40, 0.15], k=1)[0]
    aspects = rng.sample(ASPECTS, k=n_aspects)

    mentions: list[dict] = []
    clauses: list[str] = []
    for i, aspect in enumerate(aspects):
        sentiment = sentiment_for(aspect, platform, rng)
        # Ambiguous, cross-class vocabulary pool for a share of mentions.
        pool = (
            AMBIGUOUS_TEMPLATES[aspect][sentiment]
            if rng.random() < AMBIGUOUS_SHARE
            else TEMPLATES[aspect][sentiment]
        )
        template = rng.choice(pool)
        clause = template.format(product=product, brand=brand)

        # Simulated annotation disagreement: the stored label may differ
        # from the text's obvious polarity (see LABEL_NOISE_RATE).
        stored_sentiment = sentiment
        annotation_note = "auto-generated (synthetic demo)"
        if rng.random() < LABEL_NOISE_RATE:
            stored_sentiment = rng.choice(ADJACENT_FLIPS[sentiment])
            annotation_note = "auto-generated (synthetic demo, simulated disagreement)"

        if i > 0:
            connector = (
                rng.choice(CONNECTORS_MIXED)
                if stored_sentiment != mentions[i - 1]["sentiment"]
                else rng.choice(CONNECTORS_ADDED)
            )
            clause = connector + clause
        clauses.append(clause)
        mentions.append(
            {
                "annotation_id": f"A{review_id:05d}-{i + 1}",
                "review_id": f"R{review_id:05d}",
                "aspect": aspect,
                "sentiment": stored_sentiment,
                "evidence_phrase": clause,
                "annotation_status": annotation_note,
                "annotator_id": "generate_dataset.py v2",
            }
        )

    text = " ".join(clauses)
    rating = rating_from(mentions, rng)
    start = date(2025, 6, 1)
    review_date = start + timedelta(days=rng.randint(0, 365))
    return text, mentions, rating, review_date.isoformat()


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--n-reviews", type=int, default=2000)
    parser.add_argument("--seed", type=int, default=SEED_DEFAULT)
    args = parser.parse_args()

    rng = random.Random(args.seed)
    OUT_DIR.mkdir(parents=True, exist_ok=True)

    review_rows: list[dict] = []
    annotation_rows: list[dict] = []
    seen_texts: set[str] = set()
    review_id = 0

    while len(review_rows) < args.n_reviews:
        review_id += 1
        platform = weighted_choice(rng, PLATFORMS)
        category = weighted_choice(rng, CATEGORY_WEIGHTS)
        _, product = rng.choice(PRODUCTS[category])
        text, mentions, rating, review_date = build_review(
            review_id, platform, category, product, rng
        )

        # Documented dedup rule: exact-duplicate review texts are dropped.
        if text in seen_texts:
            continue
        seen_texts.add(text)

        review_rows.append(
            {
                "review_id": f"R{review_id:05d}",
                "review_text": text,
                "marketplace": platform,
                "product_category": category,
                "product_name": product,
                "rating": rating,
                "review_date": review_date,
                "source_url": "",
                "collection_date": date.today().isoformat(),
                "data_origin": "synthetic-demo-v1",
            }
        )
        annotation_rows.extend(mentions)

    reviews_path = OUT_DIR / "reviews.csv"
    annotations_path = OUT_DIR / "aspect_annotations.csv"
    with reviews_path.open("w", newline="") as f:
        csv.DictWriter(f, fieldnames=list(review_rows[0])).writeheader()
        csv.DictWriter(f, fieldnames=list(review_rows[0])).writerows(review_rows)
    with annotations_path.open("w", newline="") as f:
        csv.DictWriter(f, fieldnames=list(annotation_rows[0])).writeheader()
        csv.DictWriter(f, fieldnames=list(annotation_rows[0])).writerows(
            annotation_rows
        )

    print(f"reviews:    {len(review_rows)} -> {reviews_path}")
    print(f"annotations:{len(annotation_rows)} -> {annotations_path}")


if __name__ == "__main__":
    main()